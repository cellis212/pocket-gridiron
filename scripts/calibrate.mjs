// Measures the typical log-ratio of every matchup between ordinary starters and writes
// src/engine/calibration.js. Run it again after changing ratings, blends or the lineup optimizer.
// Usage: node scripts/calibrate.mjs
import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { POKEDEX } from '../src/data/pokedex.js';
import { makeRng } from '../src/engine/rng.js';
import { exhibitionPlayer, autoLineup, ratingOf, THEMES, themePool } from '../src/engine/lineup.js';
import { DUELS, blendValue } from '../src/engine/duels.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const rng = makeRng(20261009);

// Starters from many kinds of rosters: random draws from the whole Pokédex plus every theme team.
const lineups = [];
const addLineup = (ids, tag) => {
  const players = ids.map((s) => exhibitionPlayer(s, 100, `${tag}-${s}`));
  const lineup = autoLineup(players);
  const byId = new Map(players.map((p) => [p.pid, p]));
  lineups.push(Object.fromEntries(Object.entries(lineup).map(([slot, pid]) => [slot, ratingOf(byId.get(pid)).attrs])));
};
for (let i = 0; i < 60; i++) {
  const ids = rng.shuffle(POKEDEX.map((p) => p.id)).slice(0, 90 + rng.int(0, 120));
  addLineup(ids, `r${i}`);
}
for (const t of THEMES) {
  const ids = themePool(t.id);
  if (ids.length >= 24) addLineup(ids, t.id);
}

const ref = {};
for (const [name, d] of Object.entries(DUELS)) {
  let sum = 0;
  let n = 0;
  for (let i = 0; i < lineups.length; i++) {
    for (let j = 0; j < lineups.length; j++) {
      if (i === j) continue;
      for (const [sa, sb] of d.pairs) {
        sum += Math.log(blendValue(lineups[i][sa], d.a) / blendValue(lineups[j][sb], d.b));
        n++;
      }
    }
  }
  ref[name] = Number((sum / n).toFixed(4));
}

const out = `// Generated by scripts/calibrate.mjs from ${lineups.length} lineups. Do not edit.
// The typical log-ratio of each matchup between ordinary starters (see duels.js).
export const DUEL_REF = ${JSON.stringify(ref, null, 2)};
`;
await writeFile(join(ROOT, 'src', 'engine', 'calibration.js'), out);
console.log(out);
